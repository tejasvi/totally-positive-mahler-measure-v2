"""Emit TPCore/Lits.lean: the checker context `mkCtx iLoNum 128` as a literal (`ctxLit`), computed by the exact Python
mirror tools/tp_check_ref.py. Lean checks `mkCtx iLoNum 128 = ctxLit` by kernel evaluation (TPK/Lits.lean), so the
literal is not trusted; it only spares the kernel from recomputing the records in every shard.
usage: python3 -I gen_tp_lits.py CERT.json leaves.json OUT.lean"""
import json, sys, os
sys.argv_saved = list(sys.argv)
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tp_check_ref.py')).read().replace("if __name__ == '__main__':\n    main()", ''))
cert = Cert(sys.argv_saved[1]); lv = json.load(open(sys.argv_saved[2]))
Ilo_num, Ilo_sh = lv['Ilo']
ctx = Ctx(cert, Ilo_num, Ilo_sh)
def sgn(x): return (x > 0) - (x < 0)
recs = ', '.join(f'⟨{cert.n[i]}, {sgn(c[0])}, {c[2]}, {c[3]}⟩' for i, c in enumerate(cert.C))
out = f'''import TPCore.Check

/-! The checker context as a literal (generated by tools/gen_tp_lits.py; equality with `mkCtx iLoNum 128` is checked by
the kernel in `TPK.Lits`). -/

set_option maxRecDepth 200000

namespace TPCore

def ctxLit : Ctx where
  tab := {TAB}
  l2 := ({L2[0]}, {L2[1]})
  rs := [{recs}]
  m0hi := {cert.m0hi}
  isLo := {ctx.Islo}
  sumC := {cert.sumabsC}

end TPCore
'''
open(sys.argv_saved[3], 'w').write(out)
print('wrote', sys.argv_saved[3], len(out))
