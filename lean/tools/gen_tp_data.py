"""Generate TPCore/Data.lean (core Lean, no imports) from the certificate (read-only input).
The data are the certificate itself (polynomials, weights, nodes, G values, m0) as exact integers; derived literals
(node records, s, table, log 2) are included only together with the Lean function that recomputes them, and a theorem
in TPCore/DataOK.lean checks equality by kernel evaluation.
usage: python3 -I gen_tp_data.py CERT.json OUT_Data.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
cert_path, out = sys.argv[1], sys.argv[2]
raw = open(cert_path, 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
c = json.loads(raw)
DEC = 10 ** 10
polys = c['polys']
cw = [Fr(x) for x in c['c']]
assert all(x > 0 and x.denominator & (x.denominator - 1) == 0 for x in cw)
nodes = [Fr(x) for x in c['nodes']]; assert all((x * DEC).denominator == 1 for x in nodes)
n = [int(x * DEC) for x in nodes]
G = [Fr(x) for x in c['G']]
GS = max(x.denominator for x in G).bit_length() - 1
g = [int(x * (1 << GS)) for x in G]; assert all(Fr(gi, 1 << GS) == Gi for gi, Gi in zip(g, G))
m0 = Fr(c['m'])
assert polys[0] == [1, 0]
def lst(xs): return '[' + ', '.join(str(x) for x in xs) + ']'
L = []
L.append('/-! Data of the certificate `cert_tp_a5_9f1e5115.json`, generated by tools/gen_tp_data.py.')
L.append(f'Input SHA-256: {sha}. Core Lean only. -/')
L.append('')
L.append('set_option maxRecDepth 200000')
L.append('')
L.append('namespace TPCore')
L.append('')
L.append('/-- The polynomials `Q_j`, coefficients from the leading one down to the constant term. `Q_0 = x`. -/')
L.append('def polys : List (List Int) := ' + lst([lst(p) for p in polys]))
L.append('/-- The weights `c_j = cwNum_j / 2^cwSh_j`. -/')
L.append('def cwNum : List Nat := ' + lst([x.numerator for x in cw]))
L.append('def cwSh : List Nat := ' + lst([x.denominator.bit_length() - 1 for x in cw]))
L.append('/-- The nodes `e_i = nodes_i / 10^10`. -/')
L.append('def nodes : List Nat := ' + lst(n))
L.append(f'/-- `G_i = gvals_i / 2^GS`. -/')
L.append(f'def GS : Nat := {GS}')
L.append('def gvals : List Nat := ' + lst(g))
L.append('/-- `m₀ = m0num / m0den`. -/')
L.append(f'def m0num : Nat := {m0.numerator}')
L.append(f'def m0den : Nat := {m0.denominator}')
L.append('')
L.append('end TPCore')
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote', out, 'nodes', len(n), 'GS', GS, 'sha', sha)
