"""Emit TPCore/Leaves.lean (core Lean) from the generator output: the leaves sorted by position, as a List of Leaf
records, plus the tiling end points and the claimed lower bound of I. Untrusted hints: the checker verifies everything.
usage: python3 -I gen_tp_leaves.py leaves.json OUT.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEC = 10 ** 10
raw = open(sys.argv[1], 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
d = json.loads(raw)
L = [(Fr(l['Xp'], DEC << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEC << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
# contiguity
for a, b in zip(L, L[1:]):
    assert Fr(a[3], DEC << a[4]) == Fr(b[2], DEC << b[4]), (a, b)
assert L[0][0] == Fr(1, 2**30), L[0]
xt = Fr(L[-1][3], DEC << L[-1][4]); assert xt.denominator == 1, xt
out = []
out.append('import TPCore.Check')
out.append('')
out.append(f'/-! Leaves of the tiling, generated by tools/gen_tp_leaves.py from {sys.argv[1].split("/")[-1]} (sha256 {sha}). -/')
out.append('')
out.append('set_option maxRecDepth 200000')
out.append('')
out.append('namespace TPCore')
out.append('')
out.append(f'/-- Right end of the tiling `x_t = {xt.numerator}`; left end `x₀ = 2^-30`. -/')
out.append(f'def XT : Nat := {xt.numerator}')
out.append(f'/-- Claimed lower bound `I ≥ iLoNum / 2^128`. -/')
out.append(f'def iLoNum : Nat := {d["Ilo"][0]}')
out.append('def leaves : List Leaf := [')
items = [f'  ⟨{t[1]}, {t[2]}, {t[3]}, {t[4]}, {"true" if t[5] else "false"}, {t[6]}⟩' for t in L]
out.append(',\n'.join(items))
out.append(']')
out.append('')
out.append('end TPCore')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('leaves', len(L), 'x_t', xt, 'sha', sha)
