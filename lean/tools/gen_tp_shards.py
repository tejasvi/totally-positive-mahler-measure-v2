"""Emit the computational shard modules (N: native_decide, K: decide +kernel) from TPCore/Leaves.lean's leaf list.
Each shard checks a contiguous block of leaves between literal end points; the assembly lemma `leavesOK_append`
(TPMahler.CheckSound) joins them. usage: python3 -I gen_tp_shards.py leaves.json NCHUNK MODE(N|K) OUTDIR"""
import json, sys
from fractions import Fraction as Fr
DEC = 10 ** 10
d = json.load(open(sys.argv[1])); n = int(sys.argv[2]); mode = sys.argv[3]; outdir = sys.argv[4]
L = [(Fr(l['Xp'], DEC << l['k']), l['Xp'], l['k']) for l in d['chord']] + [(Fr(w['Xu'], DEC << w['k']), w['Xu'], w['k']) for w in d['windows']]
L.sort(key=lambda t: t[0])
N = len(L); per = -(-N // n)
starts = list(range(0, N, per))
xt = Fr(max(Fr(l['Xq'], DEC << l['k']) for l in d['chord'] + [{'Xq': w['Xv'], 'k': w['k']} for w in d['windows']]))
pref = 'TPN' if mode == 'N' else 'TPK'
tac = 'native_decide' if mode == 'N' else 'decide +kernel'
names = []
for ci, a in enumerate(starts):
    b = min(a + per, N)
    X1, k1 = L[a][1], L[a][2]
    if b < N: X2, k2 = L[b][1], L[b][2]
    else: X2, k2 = xt.numerator * DEC, 0
    name = f'Chunk{ci:03d}'
    names.append((name, a, b - a, X1, k1, X2, k2))
    src = f'''import TPCore.Lits
import TPCore.Leaves

/-! Shard {ci} of the tiling ({mode}): leaves {a} .. {b - 1}. Generated by tools/gen_tp_shards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace TPCore.{pref}

theorem chunk_{ci:03d} :
    leavesOK {'(mkCtx iLoNum 128)' if mode == 'N' else 'ctxLit'} {X1} {k1} ((leaves.drop {a}).take {b - a}) {X2} {k2} = true := by
  {tac}

end TPCore.{pref}
'''
    open(f'{outdir}/{name}.lean', 'w').write(src)
print(len(names), 'chunks of', per)
json.dump(names, open(f'{outdir}/chunks.json', 'w'))
